import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
const page = await browser.newPage({viewport:{width:390,height:664}});
await page.goto('http://127.0.0.1:5494/src/world/ui/harness.html');
await page.getByRole('button',{name:'1桌',exact:true}).click();
const button=page.getByRole('button',{name:'递上找零',exact:true});
const colors=await button.evaluate(el=>({foreground:getComputedStyle(el).color,background:getComputedStyle(el).backgroundColor}));
const luminance=rgb=>rgb.match(/\d+/g).map(Number).map(c=>c/255).map(c=>c<=.04045?c/12.92:((c+.055)/1.055)**2.4).reduce((sum,c,i)=>sum+c*[.2126,.7152,.0722][i],0);
const contrast=(a,b)=>{const x=luminance(a),y=luminance(b);return (Math.max(x,y)+.05)/(Math.min(x,y)+.05);};
const before={foreground:'rgb(251, 247, 239)',background:'rgb(241, 234, 221)'};
assert(contrast(colors.foreground,colors.background)>=4.5);
await button.click();
assert.equal(await page.locator('[data-notice]').textContent(),'pay-0');
await button.focus();await page.keyboard.press('Enter');
assert.equal(await page.locator('[data-notice]').textContent(),'pay-0');
await page.screenshot({path:'docs/evidence/world/0090/footer-after.png'});
await writeFile('docs/evidence/world/0090/footer-contrast.json',JSON.stringify({before:{...before,contrast:contrast(before.foreground,before.background)},after:{...colors,contrast:contrast(colors.foreground,colors.background)},callback:'pointer and Enter activation passed',profile:'owned harness with same primary class and contextual footer cascade as e02; e02 assembly unchanged'},null,2)+'\n');
await browser.close();
